/**
 * Writes src/app/build-version.ts with a fresh timestamp-based build id.
 *
 * Runs automatically via the npm `prebuild` / `prebuild:ssr` / `prestart` hooks,
 * so every CI deploy (Azure SWA runs `npm run build`) gets a unique id.
 *
 * The id is appended as `?v=` to runtime-fetched JSON (i18n translations) so
 * browsers and CDNs can never serve a stale file from a previous deploy —
 * a stale translations file makes raw keys like "HEADER.CTABUBBLE" visible
 * to users.
 */
const fs = require('fs');
const path = require('path');

const buildId = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 12); // e.g. 202607141830
const target = path.join(__dirname, '..', 'src', 'app', 'build-version.ts');

const content = `// AUTO-GENERATED by scripts/generate-build-version.js — do not edit by hand.
// Regenerated on every build (npm prebuild/prestart hooks).
export const BUILD_VERSION = '${buildId}';
`;

fs.writeFileSync(target, content);
console.log(`[generate-build-version] BUILD_VERSION = ${buildId}`);
